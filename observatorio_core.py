def _cod_feature(pr):
    for k in ("DPTO", "DPTO_CCDGO", "dpto_ccdgo", "dpto", "cod_dpto", "COD_DPTO"):
        if pr.get(k) not in (None, ""):
            c = cod_depto(pr[k])
            if c:
                return c
    for k in ("NOMBRE_DPT", "DPTO_CNMBR", "NOMBRE", "name", "nombre_dpto"):
        if pr.get(k):
            c = cod_por_nombre(pr[k])
            if c:
                return c
    return None


@functools.lru_cache(maxsize=1)
def _geojson():
    ultimo = "sin intentos"
    for url in CONFIG["geojson_urls"]:
        try:
            gj = http_json(url, timeout=60)
            n = 0
            for f in gj["features"]:
                c = _cod_feature(f.get("properties", {}))
                f.setdefault("properties", {})["cod"] = c
                n += c is not None
            if n >= 25:
                return gj
            ultimo = "GeoJSON sin los códigos departamentales esperados"
        except Exception as e:
            ultimo = f"{type(e).__name__}: {e}"
    try:  # respaldo: disolver municipios MGN-DANE por departamento
        from shapely.geometry import shape, mapping
        from shapely.ops import unary_union
        gm = http_json(CONFIG["geojson_mpio"], timeout=120)
        grupos = {}
        for f in gm["features"]:
            pr = f.get("properties", {})
            c = cod_depto(pr.get("DPTO_CCDGO") or str(pr.get("MPIO_CDPMP", ""))[:2])
            if c:
                grupos.setdefault(c, []).append(shape(f["geometry"]))
        feats = [dict(type="Feature", properties=dict(cod=c), geometry=mapping(unary_union(g).simplify(0.01)))
                 for c, g in grupos.items()]
        if len(feats) >= 25:
            return dict(type="FeatureCollection", features=feats)
    except Exception as e:
        ultimo += f" | respaldo MGN: {type(e).__name__}: {e}"
    raise ErrorAPI(ultimo)


