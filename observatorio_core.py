def _ping(ep):
    nombre, url = ep
    t0 = time.time()
    try:
        r = _SESION.get(url, headers=UA, timeout=12, stream=True)
        ms = int((time.time() - t0) * 1000)
        r.close()
        if r.status_code < 400:
            return nombre, "on", f"HTTP {r.status_code}", ms
        if r.status_code in (403, 429):
            return nombre, "warn", f"Respuesta restringida (HTTP {r.status_code})", ms
        return nombre, "off", f"HTTP {r.status_code}", ms
    except Exception as e:
        return nombre, "off", type(e).__name__, int((time.time() - t0) * 1000)


