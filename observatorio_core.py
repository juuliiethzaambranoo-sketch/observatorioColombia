def http_json(url, params=None, intentos=3, timeout=None):
    ultimo = "sin respuesta"
    for i in range(intentos):
        try:
            r = _SESION.get(url, params=params, headers=UA, timeout=timeout or CONFIG["timeout"])
            if r.status_code == 200:
                return r.json()
            ultimo = f"HTTP {r.status_code}"
            if r.status_code in (400, 401, 403, 404):
                break
        except requests.Timeout:
            ultimo = "tiempo de espera agotado"
        except requests.RequestException as e:
            ultimo = type(e).__name__
        except ValueError:
            ultimo = "la respuesta no es JSON válido"
            break
        time.sleep(0.8 * (i + 1))
    raise ErrorAPI(ultimo)


def soda(dataset, params, timeout=None):
    js = http_json(CONFIG["socrata"].format(dataset), params, timeout=timeout)
    if not isinstance(js, list):
        raise ErrorAPI(str(js)[:160])
    return pd.DataFrame(js)


def soda_pag(dataset, params, tope=300000, pagina=50000, timeout=60):
    """Descarga paginada (Socrata limita 50.000 filas por petición)."""
    partes, off = [], 0
    while off < tope:
        p = dict(params, **{"$limit": pagina, "$offset": off})
        d = soda(dataset, p, timeout=timeout)
        if d.empty:
            break
        partes.append(d)
        if len(d) < pagina:
            break
        off += pagina
    return pd.concat(partes, ignore_index=True) if partes else pd.DataFrame()


