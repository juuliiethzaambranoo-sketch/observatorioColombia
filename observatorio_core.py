def _l_macro_catalogo(clave):
    spec = MACROS[clave]
    vistos, intentos, motivos, t0 = set(), 0, [], time.time()
    for q in spec["consultas"]:
        if time.time() - t0 > 15:
            break
        try:
            cands = descubrir(q)
        except ErrorAPI as e:
            raise ErrorAPI(f"catálogo de datos.gov.co no disponible ({e})")
        for c in cands:
            if c["id"] in vistos or intentos >= 3 or time.time() - t0 > 15:
                continue
            vistos.add(c["id"])
            intentos += 1
            try:
                raw = soda_pag(c["id"], {}, tope=20000, pagina=20000, timeout=20)
                out, col = _estandarizar(raw, spec, clave)
                META_MACRO[clave] = dict(id=c["id"], nombre=c["nombre"], ent=c["ent"], col=col)
                return out
            except (ErrorAPI, ValueError, KeyError) as e:
                motivos.append(f"{c['id']}: {e}")
    raise ErrorAPI("ningún conjunto DANE/BanRep publicado en datos.gov.co superó la validación"
                   + (f" (último motivo: {motivos[-1]})" if motivos else " (sin candidatos)"))


