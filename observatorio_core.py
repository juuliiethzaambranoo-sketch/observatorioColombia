def _parse_fecha(s):
    """Fechas en texto: ISO (2020-05-17...) o día/mes/año (17/05/2020)."""
    s = s.astype(str).str.strip()
    iso = s.str.match(r"^\d{4}-\d{2}")
    f = pd.to_datetime(s.where(iso), errors="coerce")
    dmy = pd.to_datetime(s.where(~iso), errors="coerce", dayfirst=True)
    return f.fillna(dmy)


def _ev_mensual(ds):
    base = "{c} as d, date_extract_y(fecha_hecho) as y, date_extract_m(fecha_hecho) as m, sum(cantidad) as n"
    ultimo = ErrorAPI("sin respuesta")
    for campo in ("cod_depto", "departamento"):
        try:
            df = soda(ds, {"$select": base.format(c=campo), "$group": "d, y, m", "$limit": 50000}, timeout=60)
        except ErrorAPI as e:
            ultimo = e
            continue
        if df.empty or "d" not in df:
            continue
        df["cod"] = df["d"].map(cod_depto if campo == "cod_depto" else cod_por_nombre)
        df = df.dropna(subset=["cod"])
        if df.cod.nunique() >= 20:
            df["fecha"] = pd.to_datetime(dict(year=num(df.y), month=num(df.m), day=1), errors="coerce")
            df["valor"] = num(df.n)
            df = df.dropna(subset=["fecha", "valor"])
            return df.groupby(["cod", "fecha"], as_index=False).valor.sum()
    # Plan alterno: fecha_hecho/cantidad pueden ser texto → se agrupa por día y se interpreta en pandas
    for agg in ("sum(cantidad)", "count(1)"):
        try:
            df = soda_pag(ds, {"$select": f"departamento as d, fecha_hecho as f, {agg} as n", "$group": "d, f",
                               "$order": "d, f"}, tope=500000, timeout=90)
        except ErrorAPI as e:
            ultimo = e
            continue
        if df.empty or "f" not in df:
            continue
        df["cod"] = df["d"].map(cod_por_nombre)
        df["fecha"] = _parse_fecha(df["f"]).dt.to_period("M").dt.to_timestamp()
        df["valor"] = num(df.n)
        df = df.dropna(subset=["cod", "fecha", "valor"])
        if df.cod.nunique() >= 20:
            return df.groupby(["cod", "fecha"], as_index=False).valor.sum()
    raise ErrorAPI(f"{ultimo}; o cobertura departamental insuficiente")


def _l_coca():
    df = soda(FUENTES["coca"]["id"], {"$limit": 5000}, timeout=60)
    anios = sorted(int(c[1:]) for c in df.columns if c.startswith("_") and c[1:].isdigit())
    if not anios or "coddepto" not in df:
        raise ErrorAPI("estructura inesperada del conjunto")
    df["cod"] = df["coddepto"].map(cod_depto)
    df = df.dropna(subset=["cod"])
    larg = df.melt(id_vars="cod", value_vars=[f"_{a}" for a in anios], var_name="anio", value_name="coca")
    larg["anio"] = larg.anio.str[1:].astype(int)
    larg["coca"] = num(larg.coca)
    out = larg.groupby(["cod", "anio"], as_index=False).coca.sum(min_count=1).dropna()
    if out.cod.nunique() < 8:
        raise ErrorAPI("cobertura departamental insuficiente")
    return out


def _l_edu():
    df = soda_pag(FUENTES["edu"]["id"], {"$select": "a_o, c_digo_departamento, cobertura_neta, deserci_n"})
    if df.empty or "a_o" not in df:
        raise ErrorAPI("estructura inesperada del conjunto")
    df["cod"] = df["c_digo_departamento"].map(cod_depto)
    df["anio"] = num(df.a_o)
    df["cob"], df["des"] = num(df.get("cobertura_neta")), num(df.get("deserci_n"))
    df = df.dropna(subset=["cod", "anio"])
    df["anio"] = df.anio.astype(int)
    out = df.groupby(["cod", "anio"], as_index=False)[["cob", "des"]].mean()
    if out.cod.nunique() < 20:
        raise ErrorAPI("cobertura departamental insuficiente")
    return out


def _l_trm():
    df = soda_pag(FUENTES["trm"]["id"], {"$select": "valor, vigenciadesde", "$order": "vigenciadesde",
                                         "$where": "vigenciadesde >= '2000-01-01T00:00:00'"}, tope=60000)
    if df.empty or "valor" not in df:
        raise ErrorAPI("estructura inesperada del conjunto")
    df["fecha"] = pd.to_datetime(df.vigenciadesde, errors="coerce")
    df["valor"] = num(df.valor)
    df = df.dropna(subset=["fecha", "valor"])
    m = df.set_index("fecha").valor.resample("MS").mean().dropna()
    m = m[m.index < pd.Timestamp(hoy().year, hoy().month, 1)]  # se excluye el mes en curso (incompleto)
    return pd.DataFrame({"cod": "00", "fecha": m.index, "valor": m.values})


