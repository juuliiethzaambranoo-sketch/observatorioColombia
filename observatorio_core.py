    js = http_json(f"https://api.worldbank.org/v2/country/COL/indicator/{code}", {"format": "json", "per_page": 200},
                   intentos=2, timeout=25)
    if not (isinstance(js, list) and len(js) >= 2 and js[1]):
        raise ErrorAPI("sin datos para este indicador")
    filas = [(pd.Timestamp(int(r["date"]), 1, 1), float(r["value"])) for r in js[1]
             if r.get("value") is not None and str(r.get("date", "")).isdigit()]
    if len(filas) < 3:
        raise ErrorAPI("serie con muy pocos datos")
    out = pd.DataFrame(filas, columns=["fecha", "valor"]).sort_values("fecha").reset_index(drop=True)
    out["cod"] = "00"
    lo, hi = MACROS[clave]["rango"]
    if not out.valor.between(lo, hi).all():
        raise ErrorAPI("valores fuera del rango esperado")
    META_MACRO[clave] = dict(id=code, nombre=f"Banco Mundial WDI · {code}", ent="Banco Mundial (WDI)", col=code, anual=True)
    return out[["cod", "fecha", "valor"]]


