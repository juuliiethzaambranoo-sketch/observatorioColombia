def f1(x, d=1):
    return f"{x:,.{d}f}".replace(",", "X").replace(".", ",").replace("X", ".")


def _delta(v, p, bueno_baja=True):
    if p is None or pd.isna(p) or p == 0:
        return "", ""
    d = (v / p - 1) * 100
    tono = ("ok" if d < 0 else "alert") if bueno_baja else ("ok" if d > 0 else "alert")
    return f'{"▲" if d >= 0 else "▼"} {f1(abs(d), 1)} %', tono


