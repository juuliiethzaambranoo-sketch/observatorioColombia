@functools.lru_cache(maxsize=4)
def _panel_b(b, ver=0):
    partes = []
    for k in ("hom", "sec", "vif"):
        d = cargar(k)
        if d is None:
            continue
        d = d.assign(anio=d.fecha.dt.year)
        meses = d.groupby("anio").fecha.nunique()
        completos = meses[meses == 12].index
        d = d[d.anio.isin(completos) & (d.anio < hoy().year)]
        if d.empty:
            continue
        a = d.groupby(["cod", "anio"], as_index=False).valor.sum().rename(columns={"valor": k})
        # los conjuntos de eventos solo registran los casos ocurridos: ausencia en un año completo = 0 casos
        malla = pd.MultiIndex.from_product([sorted(d.cod.unique()), sorted(completos)], names=["cod", "anio"])
        a = a.set_index(["cod", "anio"]).reindex(malla, fill_value=0).reset_index()
        partes.append(a.set_index(["cod", "anio"]))
    c = cargar("coca")
    if c is not None:
        partes.append(c.set_index(["cod", "anio"]))
    e = cargar("edu")
    if e is not None:
        partes.append(e.set_index(["cod", "anio"]))
    for k in ("ipm", "desempleo"):
        m = cargar(f"m_{k}") if ESTADO.get(f"m_{k}", {}).get("ok") else None
        if m is not None and (m.cod != "00").any():
            x = m[m.cod != "00"].assign(anio=lambda d: d.fecha.dt.year).groupby(["cod", "anio"]).valor.mean().rename(k)
            partes.append(x.to_frame())
    if not partes:
        return None
    p = pd.concat(partes, axis=1).sort_index().reset_index()
    p["depto"] = p.cod.map(DEPTOS)
    return p[p.anio >= CONFIG["anio_min"]].reset_index(drop=True)


