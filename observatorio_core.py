def estimar_panel(y_k, x_k, rezago, fe):
    p = panel()
    if p is None or y_k not in p.columns or x_k not in p.columns:
        raise ErrorAPI("alguna de las variables no está disponible en tiempo real")
    d = p[["cod", "anio", y_k, x_k]].copy().sort_values(["cod", "anio"])
    d["x"] = d.groupby("cod")[x_k].shift(rezago) if rezago else d[x_k]
    d = d.rename(columns={y_k: "y"}).dropna(subset=["y", "x"])
    d["ly"], d["lx"] = np.log1p(d.y.clip(lower=0)), np.log1p(d.x.clip(lower=0))
    if len(d) < 60 or d.cod.nunique() < 8:
        raise ErrorAPI(f"datos insuficientes para estimar (N={len(d)}, departamentos={d.cod.nunique()})")
    f = "ly ~ lx + C(cod)" + (" + C(anio)" if fe == "Departamento + año" else "")
    res = smf.ols(f, d).fit(cov_type="cluster", cov_kwds={"groups": pd.factorize(d.cod)[0]})
    ci = res.conf_int().loc["lx"]
    return dict(b=res.params["lx"], se=res.bse["lx"], lo=ci[0], hi=ci[1], pv=res.pvalues["lx"], n=int(res.nobs),
                g=d.cod.nunique(), r2=res.rsquared)


def simular(y_k, x_k, cod, delta, dur, rezago, horizonte, fe):
    try:
        if y_k == x_k:
            raise ErrorAPI("elija un impulsor distinto del resultado")
        e = estimar_panel(y_k, x_k, int(rezago), fe)
        p = panel()
        sy, sx = serie_agregada(p, y_k, cod).dropna(), serie_agregada(p, x_k, cod).dropna()
        if len(sy) < 6 or sx.empty:
            raise ErrorAPI("serie histórica del territorio demasiado corta")
    except ErrorAPI as ex:
        return fig_aviso(f"{ex}"), pd.DataFrame(), aviso(f"Simulación no disponible: {ex}", "err")
    h = int(horizonte)
    base = sy.iloc[-10:]
    t = np.arange(len(base))
    res = sm.OLS(base.values, sm.add_constant(t, has_constant="add")).fit()
    fut = np.arange(len(base), len(base) + h)
    sf = res.get_prediction(sm.add_constant(fut, has_constant="add")).summary_frame(alpha=.05)
    anios = np.arange(sy.index.max() + 1, sy.index.max() + 1 + h)
    inercial = np.clip(sf["mean"].values, 0, None)
    x0 = float(sx.iloc[-1])
    dlx = np.log1p(x0 * (1 + delta / 100)) - np.log1p(x0)
    # el efecto se activa pasados 'rezago' años y se acumula linealmente durante 'dur' años
    fase = np.clip((np.arange(1, h + 1) - int(rezago)) / max(1, int(dur)), 0, 1)

    def esc(beta):
        return np.clip((1 + inercial) * np.exp(beta * dlx * fase) - 1, 0, None)
    s_c, s_lo, s_hi = esc(e["b"]), esc(min(e["lo"], e["hi"])), esc(max(e["lo"], e["hi"]))
    banda_lo, banda_hi = np.minimum(s_lo, s_hi), np.maximum(s_lo, s_hi)
    f = go.Figure()
    f.add_trace(go.Scatter(
        x=sy.index, y=sy.values, name="Histórico oficial", mode="lines",
        line=dict(color="#E2E8F0", width=2.2),
        hovertemplate="%{x}: %{y:,.2f}<extra>Histórico oficial</extra>",
    ))
    f.add_trace(go.Scatter(
        x=anios, y=inercial, name="Escenario inercial (tendencia)", mode="lines+markers",
        line=dict(color="#94A3B8", dash="dot", width=3),
        hovertemplate="%{x}: %{y:,.2f}<extra>Inercial</extra>",
    ))
    f.add_trace(go.Scatter(
        x=list(anios) + list(anios[::-1]), y=list(banda_hi) + list(banda_lo[::-1]), fill="toself",
        fillcolor="rgba(0,56,147,.28)", line=dict(width=0), name="IC 95 % de la elasticidad", hoverinfo="skip",
    ))
    f.add_trace(go.Scatter(
        x=anios, y=s_c, name=f"Escenario: {delta:+.0f} % en {etq(x_k)}", mode="lines+markers",
        line=dict(color=AMARILLO, width=3),
        hovertemplate="%{x}: %{y:,.2f}<extra>Escenario</extra>",
    ))
    nom = "Nacional" if cod == "00" else DEPTOS[cod]
    estilo(f, f"{etq(y_k)} · {nom}: inercial vs. simulación ({VARS[y_k]['unidad']})", 520, hovermode="x unified")
    tab = pd.DataFrame({"Año": anios, "Inercial": inercial.round(2), "Escenario": s_c.round(2),
                        "Diferencia": (s_c - inercial).round(2), "IC inf.": banda_lo.round(2), "IC sup.": banda_hi.round(2)})
    sig = "estadísticamente significativa (p<0,05)" if e["pv"] < .05 else "NO significativa al 5 %: interprete con cautela"
    info = (f'<div class="aviso ok"><b>Motor econométrico:</b> regresión log-log de panel con efectos fijos ({fe.lower()}), errores '
            f'agrupados por departamento. Elasticidad estimada β = <b>{e["b"]:.3f}</b> (IC 95 %: {e["lo"]:.3f} a {e["hi"]:.3f}; '
            f'{sig}). N={e["n"]} obs., {e["g"]} departamentos, rezago {int(rezago)} año(s).<br>'
            f'<small>Es una asociación estadística estimada con datos oficiales, no una prueba causal; úsela como escenario ilustrativo.</small></div>')
    return f, tab, info


