def ui(tipos):
    """Decorador: si un callback falla, informa el error en cada salida en lugar de romper la interfaz.
    Soporta callbacks síncronos y asíncronos."""
    def fallo(e):
        msg = f"{type(e).__name__}: {e}"
        out = [aviso(msg, "err") if t == "h" else fig_aviso(msg) if t == "p" else pd.DataFrame() if t == "d" else None
               for t in tipos]
        if not out:
            return None
        return out[0] if len(out) == 1 else tuple(out)

    def deco(fn):
        if inspect.iscoroutinefunction(fn):
            @functools.wraps(fn)
            async def wa(*a):
                try:
                    return await fn(*a)
                except Exception as e:
                    return fallo(e)
            return wa

        @functools.wraps(fn)
        def w(*a):
            try:
                return fn(*a)
            except Exception as e:
                return fallo(e)
        return w
    return deco


