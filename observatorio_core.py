_LOCKS, _LK = {}, threading.Lock()


def _lock(k):
    with _LK:
        return _LOCKS.setdefault(k, threading.Lock())


def cargar(clave):
    """Devuelve el DataFrame real o None (y deja el motivo en ESTADO). Nunca fabrica datos.
    Un candado por fuente evita descargas duplicadas cuando varias pestañas piden lo mismo."""
    with _lock(clave):
        try:
            df = _cargar(clave, _bucket())
            ex = META_MACRO[clave[2:]]["id"] if clave.startswith("m_") and clave[2:] in META_MACRO else ""
            registrar(clave, True, "Datos obtenidos de la API", filas=len(df), id=ex or FUENTES.get(clave, {}).get("id", ""))
            return df
        except Exception as e:
            registrar(clave, False, f"{type(e).__name__}: {e}")
            return None


