def _estandarizar(df, spec, clave):
    """Convierte un conjunto crudo en (fecha, cod, valor) o lanza ValueError con el motivo del rechazo."""
    if df.empty or len(df) < 8:
        raise ValueError("muy pocas filas")
    cols = {c: ln(c) for c in df.columns}
    c_anio = next((c for c, l in cols.items() if l in ("a_o", "ano", "anio", "vigencia", "year") or l.startswith("a_o")), None)
    c_mes = next((c for c, l in cols.items() if l in ("mes", "month")), None)
    c_fecha = next((c for c, l in cols.items() if ("fecha" in l or l.startswith("periodo")) and c != c_anio), None)
    c_dep = next((c for c, l in cols.items() if "departamento" in l and "cod" not in l and "c_digo" not in l), None)
    c_cod = next((c for c, l in cols.items() if re.search(r"(cod|c_digo).*(dep|dpto)|coddepto", l)), None)
    # filtrar filas "Total" si existen categorías
    for c in df.columns:
        if not pd.api.types.is_numeric_dtype(df[c]) and df[c].nunique() <= 30:
            tot = df[c].astype(str).map(norm).isin(["TOTAL", "TOTAL NACIONAL", "NACIONAL"])
            if tot.any() and c not in (c_dep,):
                df = df[tot]
    if c_fecha is not None:
        fecha = pd.to_datetime(df[c_fecha], errors="coerce")
        if fecha.notna().mean() < 0.9:
            raise ValueError("fecha no interpretable")
    elif c_anio is not None:
        a = num(df[c_anio])
        if c_mes is not None:
            m = num(df[c_mes])
            if m.isna().mean() > 0.5:
                m = df[c_mes].astype(str).map(lambda x: MESES_ES.get(sin_tildes(x).lower().strip()))
            fecha = pd.to_datetime(dict(year=a, month=m.fillna(1), day=1), errors="coerce")
        else:
            fecha = pd.to_datetime(dict(year=a, month=1, day=1), errors="coerce")
    else:
        raise ValueError("sin columna temporal")
    cod = None
    if c_cod is not None:
        cod = df[c_cod].map(cod_depto)
    elif c_dep is not None:
        cod = df[c_dep].map(cod_por_nombre)
    usados = {c_fecha, c_anio, c_mes, c_dep, c_cod}
    mejor = None
    lo, hi = spec["rango"]
    for kw in spec["kw"]:
        for c, l in cols.items():
            if c in usados or kw not in l:
                continue
            v = num(df[c])
            if v.notna().mean() < 0.8:
                continue
            q = v.quantile([0.05, 0.95])
            if clave == "ipc" and kw == "indice":
                mejor = (c, v, True)
            elif q.iloc[0] >= lo and q.iloc[1] <= hi:
                mejor = (c, v, False)
            if mejor:
                break
        if mejor:
            break
    if not mejor:
        raise ValueError("sin columna de valor reconocible dentro del rango esperado")
    col, v, es_indice = mejor
    out = pd.DataFrame({"fecha": fecha, "cod": cod if cod is not None else None, "valor": v}).dropna(subset=["fecha", "valor"])
    if cod is None:
        out["cod"] = "00"
    else:
        out["cod"] = out["cod"].where(out["cod"].notna(), None)
        out = out.dropna(subset=["cod"])
    if out.empty:
        raise ValueError("sin filas utilizables")
    if out.duplicated(["fecha", "cod"]).any():
        out = out.groupby(["fecha", "cod"], as_index=False).valor.mean() if clave != "pib" else None
        if out is None:
            raise ValueError("filas duplicadas por periodo (requiere filtro de categoría)")
    out = out.sort_values(["cod", "fecha"]).reset_index(drop=True)
    if es_indice:  # nivel del índice → variación anual calculada (no inventada)
        out["valor"] = out.groupby("cod").valor.pct_change(12) * 100
        out = out.dropna(subset=["valor"])
        col += " (variación anual calculada a partir del índice)"
    return out, col


