def _macro_manual(clave, cfg):
    """Conjunto elegido por el usuario: columnas de tiempo, territorio (opcional) y valor."""
    ds, c_t, c_d, c_v = cfg["id"], cfg["t"], cfg.get("d"), cfg["v"]
    df = soda_pag(ds, {}, tope=100000, pagina=50000, timeout=60)
    for c in (c_t, c_v) + ((c_d,) if c_d else ()):
        if c not in df.columns:
            raise ErrorAPI(f"la columna «{c}» no existe; columnas: {', '.join(df.columns[:25])}")
    t = df[c_t]
    if num(t).between(1900, 2100).mean() > 0.9:
        fecha = pd.to_datetime(dict(year=num(t), month=1, day=1), errors="coerce")
    else:
        fecha = pd.to_datetime(t, errors="coerce")
    v = num(df[c_v].astype(str).str.replace(",", ".", regex=False))
    out = pd.DataFrame({"fecha": fecha, "valor": v})
    out["cod"] = df[c_d].map(lambda x: cod_depto(x) or cod_por_nombre(x)) if c_d else "00"
    out = out.dropna(subset=["fecha", "valor", "cod"])
    lo, hi = MACROS[clave]["rango"]
    if out.empty:
        raise ErrorAPI("sin filas utilizables con esas columnas")
    if clave != "pib" and not out.valor.between(lo, hi).mean() > 0.8:
        raise ErrorAPI(f"los valores no están en el rango esperado para este indicador ({lo} a {hi})")
    out = out.groupby(["cod", "fecha"], as_index=False).valor.mean()
    META_MACRO[clave] = dict(id=ds, nombre=f"Conjunto elegido por el usuario ({ds})", ent="datos.gov.co", col=c_v)
    return out.sort_values(["cod", "fecha"]).reset_index(drop=True)


