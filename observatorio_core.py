def clusteres(ks, k, a0, a1):
    p = panel()
    if p is None:
        return fig_aviso("Sin datos de panel."), fig_aviso("Sin datos de panel."), pd.DataFrame(), pd.DataFrame(), None
    ks = [x for x in ks if x in p.columns]
    if len(ks) < 2:
        v = fig_aviso("Seleccione al menos dos indicadores disponibles.")
        return v, v, pd.DataFrame(), pd.DataFrame(), None
    ventana = p[(p.anio >= a0) & (p.anio <= a1)].groupby("cod")[ks].mean()
    ventana = ventana.dropna(thresh=len(ks))  # sin imputación: solo territorios con todos los indicadores
    if ventana.shape[0] < max(6, k + 2):
        v = fig_aviso(f"Solo {ventana.shape[0]} territorios tienen todos los indicadores en el periodo; insuficiente para {k} grupos.")
        return v, v, pd.DataFrame(), pd.DataFrame(), None
    X = ventana.copy()
    for c in ks:
        if VARS[c]["log"]:
            X[c] = np.log1p(X[c].clip(lower=0))
    Z = StandardScaler().fit_transform(X)
    sil = []
    for kk in range(2, min(7, ventana.shape[0] - 1)):
        lab = KMeans(kk, n_init=10, random_state=CONFIG["semilla"]).fit_predict(Z)
        sil.append((kk, silhouette_score(Z, lab)))
    km = KMeans(k, n_init=10, random_state=CONFIG["semilla"]).fit(Z)
    # etiquetar grupos ordenados por puntaje compuesto (mayor = mejor situación socioeconómica)
    signo = np.array([VARS[c]["sentido"] for c in ks])
    score = (Z * signo).mean(axis=1)
    orden = pd.Series(score).groupby(km.labels_).mean().sort_values(ascending=False).index.tolist()
    nombre = {g: f"Grupo {i + 1}" + (" (mejor situación)" if i == 0 else " (mayor rezago)" if i == len(orden) - 1 else "")
              for i, g in enumerate(orden)}
    ventana["Grupo"] = [nombre[g] for g in km.labels_]
    pc = PCA(2, random_state=CONFIG["semilla"]).fit(Z)
    C2 = pc.transform(Z)
    dd = pd.DataFrame({"PC1": C2[:, 0], "PC2": C2[:, 1], "Grupo": ventana.Grupo.values,
                       "Departamento": [DEPTOS[c] for c in ventana.index]})
    fs = px.scatter(dd, x="PC1", y="PC2", color="Grupo", text="Departamento", color_discrete_sequence=PAL,
                    category_orders={"Grupo": [nombre[g] for g in orden]},
                    hover_data={"PC1": ":.2f", "PC2": ":.2f", "Departamento": True})
    fs.update_traces(textposition="top center", textfont_size=10,
                     marker=dict(size=12, line=dict(width=1, color="rgba(248,250,252,.55)")))
    estilo(fs, f"K-Means (k={k}) en el plano de componentes principales "
               f"({pc.explained_variance_ratio_.sum() * 100:.0f} % de la varianza)", 560)
    perfil = ventana.groupby("Grupo")[ks].mean().round(2).rename(columns={c: etq(c) for c in ks})
    perfil["N.º de departamentos"] = ventana.groupby("Grupo").size()
    perfil = perfil.reset_index()
    sil_t = pd.DataFrame(sil, columns=["k", "Silueta"]).round(3)
    sil_t["Mejor"] = ["✔" if v == sil_t.Silueta.max() else "" for v in sil_t.Silueta]
    mp = ventana.reset_index()[["cod", "Grupo"]].rename(columns={"Grupo": "valor"})
    mp["_hover"] = [f"<b>{html.escape(DEPTOS.get(c, c))}</b><br>{html.escape(str(g))}"
                    for c, g in zip(mp.cod, mp.valor)]
    fm = fig_mapa(mp, "Territorios agrupados por perfil socioeconómico", discreto=True, hover_col="_hover")
    return fs, fm, perfil, sil_t, None


